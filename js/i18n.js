function getLang() { return localStorage.getItem("chopa_lang") || "en"; }
function setLanguage(lang) { localStorage.setItem("chopa_lang", lang); location.reload(); }
function t(key) {
  const lang = getLang();
  return (I18N[lang] && I18N[lang][key]) ?? I18N.en[key] ?? key;
}
function tView(viewKey) {
  const lang = getLang();
  const map = (I18N[lang] && I18N[lang].view_titles) || I18N.en.view_titles;
  return map[viewKey] || I18N.en.view_titles[viewKey] || [viewKey, ""];
}
